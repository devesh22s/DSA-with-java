public class Array1{
    public static void main(String[] args) {

        //  arrays -> it is the collection of elements of the same data type
        int [] arr = new int[5]; // initialization
        int [] arr1 = {1,12,3,4};  // initialization + declaration
        System.out.println(arr);


        //  for each loop - used in collection of elements
        for(int i : arr1){
            System.out.println(i);
        }



    
}
}